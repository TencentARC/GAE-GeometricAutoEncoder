"""Visualize the repository and synthetic camera paths on one example scene.

The synthetic paths are generated by the same helper used by
``scripts/eval/eval_generation.py``; this script is intentionally a diagnostic
tool so trajectory geometry can be checked independently of the video model.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

# Running a file under ``scripts/demo`` does not put the repository root on
# ``sys.path``. Add it explicitly so this diagnostic uses the exact trajectory
# implementation from the evaluator.
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from scripts.demo.trajectory_utils import synthesize_free_trajectory, path_length, trajectory_extent


def _plot_paths(paths: dict[str, np.ndarray], output: Path, title: str) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    colors = {
        "Example poses": "#222222",
        "Wander": "#4285f4",
        "Orbit": "#34a853",
        "Spiral": "#a142f4",
        "Drive": "#ea4335",
    }
    fig, axes = plt.subplots(2, 3, figsize=(17, 10), constrained_layout=True)
    axes = axes.ravel()
    all_pos = np.concatenate([pose[:, :3, 3] for pose in paths.values()], axis=0)
    def _limits(values: np.ndarray, frac: float = 0.08) -> tuple[float, float]:
        lo, hi = float(values.min()), float(values.max())
        span = max(hi - lo, 1e-3)
        pad = span * frac
        return lo - pad, hi + pad
    top_xlim = _limits(all_pos[:, 0])
    top_ylim = _limits(all_pos[:, 2])
    side_ylim = _limits(all_pos[:, 1])
    for ax, (name, pose) in zip(axes, paths.items()):
        pos = pose[:, :3, 3]
        # World coordinates: x horizontal, z forward/depth, y vertical.
        ax.plot(pos[:, 0], pos[:, 2], color=colors[name], lw=2.2)
        ax.scatter(pos[0, 0], pos[0, 2], c="#1a73e8", s=55, zorder=3, label="start")
        ax.scatter(pos[-1, 0], pos[-1, 2], c="#d93025", s=55, zorder=3, label="end")
        stride = max(1, len(pos) // 10)
        fwd = -pose[:, :3, 2]
        scale = max(np.ptp(pos[:, 0]), np.ptp(pos[:, 2]), 1e-3) * 0.10
        ax.quiver(pos[::stride, 0], pos[::stride, 2],
                  fwd[::stride, 0], fwd[::stride, 2],
                  color=colors[name], alpha=0.75, angles="xy",
                  scale_units="xy", scale=1.0 / scale, width=0.003)
        ax.set_title(name)
        ax.set_xlabel("world x")
        ax.set_ylabel("world z (depth)")
        ax.grid(alpha=0.25)
        ax.set_aspect("equal", adjustable="box")
        ax.set_xlim(*top_xlim)
        ax.set_ylim(*top_ylim)
        ax.legend(loc="best", fontsize=8)

    # Looking along world x shows vertical motion against forward depth z.
    ax = axes[-1]
    ax.clear()
    for name, pose in paths.items():
        pos = pose[:, :3, 3]
        ax.plot(pos[:, 2], pos[:, 1], color=colors[name], lw=2.0, label=name)
    ax.set_title("Side view (world z / y)")
    ax.set_xlabel("world z (depth)")
    ax.set_ylabel("world y (up)")
    ax.set_xlim(*top_ylim)
    ax.set_ylim(*side_ylim)
    ax.grid(alpha=0.25)
    ax.legend(fontsize=8)
    fig.suptitle(title, fontsize=16)
    fig.savefig(output, dpi=180)
    plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--poses", type=Path,
        default=Path("examples/scenes/forest_lake_trail_poses.npz"),
        help="repository pose file used as Example camera path and anchor",
    )
    parser.add_argument("--num-views", type=int, default=81)
    parser.add_argument("--speed", type=float, default=0.06)
    parser.add_argument("--yaw-deg", type=float, default=24.0)
    parser.add_argument("--pitch-deg", type=float, default=6.0)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--output", type=Path,
                        default=Path("results/trajectory_diagnostics"))
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)

    data = np.load(args.poses)
    gt = np.asarray(data["c2w"], dtype=np.float64)
    if gt.ndim != 3 or gt.shape[1:] != (4, 4):
        raise ValueError(f"expected c2w [N,4,4], got {gt.shape}")
    anchor = gt[0]
    n = min(int(args.num_views), len(gt))
    paths: dict[str, np.ndarray] = {"Example poses": gt[:n]}
    stats: dict[str, dict[str, object]] = {}
    for name, motion in (("Wander", "wander"), ("Orbit", "orbit"),
                         ("Spiral", "spiral"), ("Drive", "drive")):
        paths[name] = np.asarray(synthesize_free_trajectory(
            anchor, n, motion=motion, speed=args.speed,
            yaw_deg=args.yaw_deg, pitch_deg=args.pitch_deg, seed=args.seed, target_extents_xyz=np.ptp(gt[:n, :3, 3], axis=0)))

    for name, pose in paths.items():
        pos = pose[:, :3, 3]
        delta = np.diff(pos, axis=0)
        fwd = -pose[:, :3, 2]
        stats[name] = {
            "num_views": int(len(pos)),
            "extent_xyz": np.ptp(pos, axis=0).round(6).tolist(),
            "net_delta_xyz": (pos[-1] - pos[0]).round(6).tolist(),
            "path_length": float(np.linalg.norm(delta, axis=1).sum()),
            "forward_projection": float(np.sum(np.sum(delta * fwd[:-1], axis=1))),
        }
        np.savez_compressed(args.output / f"{name.lower().replace(' ', '_')}_poses.npz",
                            c2w=pose)
    (args.output / "stats.json").write_text(json.dumps(stats, indent=2), encoding="utf-8")
    _plot_paths(paths, args.output / "example1_all_camera_motions.png",
                f"Example 1 camera motions — {args.poses.stem} ({n} views)")
    print(json.dumps(stats, indent=2))
    print(f"saved: {args.output / 'example1_all_camera_motions.png'}")


if __name__ == "__main__":
    main()
